  static List<String> districtsOf(String division) {
    return all
        .where((e) => e.division == division)
        .map((e) => e.district)
        .toList();
  }

  static BangladeshLocation? find(String division, String district) {
    for (final location in all) {
      if (location.division == division &&
          location.district == district) {
        return location;
      }
    }
