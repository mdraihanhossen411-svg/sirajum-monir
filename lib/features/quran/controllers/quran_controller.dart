class QuranController extends ChangeNotifier {
  final QuranService _service = QuranService();

  final List<SurahModel> _surahList = [];
  List<SurahModel> get surahList => List.unmodifiable(_surahList);

  bool _isLoading = false;
  bool get isLoading => _isLoading;

  String? _error;
  String? get error => _error;

  Future<void> loadSurahs() async {
    if (_isLoading) return;

    _isLoading = true;
    _error = null;
    notifyListeners();

    try {
      final surahMetadata = await _service.loadSurahList();

      _surahList
        ..clear()
        ..addAll(
          surahMetadata.map(
            (data) => SurahModel.fromJson(
              Map<String, dynamic>.from(data as Map),
            ),
          ),
        );
    } catch (e) {
      _error = e.toString();
      debugPrint('Quran Core Error: $e');
    }

    _isLoading = false;
    notifyListeners();
  }

  SurahModel? getSurahById(int id) {
    try {
      return _surahList.firstWhere((surah) => surah.id == id);
    } catch (_) {
      return null;
    }
  }

